import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
const main=page.locator('[data-avatar] .eli-illustration-main').first();
const secondary=page.locator('[data-avatar] .eli-illustration-small').first();
await main.waitFor();
assert.ok((await main.getAttribute('src')).includes('outfit-'));
await page.locator('button.mini-outfit[data-outfit="cream"]').click();
assert.ok((await main.getAttribute('src')).includes('outfit-cream.webp'));
await page.locator('button[data-mood="happy"]').first().click();
assert.ok((await main.getAttribute('src')).includes('mood-happy.webp'));
assert.ok((await secondary.getAttribute('src')).includes('outfit-cream.webp'));
assert.equal(await main.evaluate(img=>img.naturalWidth>0),true);
assert.equal(await secondary.evaluate(img=>img.naturalWidth>0),true);
assert.equal(await page.locator('#heroSceneStrip button').count(),4);
await page.locator('#heroSceneStrip button[data-room="rain"]').click();
assert.equal(await page.locator('#hero').getAttribute('data-scene'),'rain');
assert.ok((await page.locator('#heroTagline').innerText()).includes('雨声'));
await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
await page.reload({waitUntil:'networkidle'});
assert.equal(await page.locator('#hero').getAttribute('data-scene'),'rain');
await page.locator('button[data-go="rooms"]').first().click();
assert.equal(await page.locator('#roomSelections .selection-card').count(),4);
assert.ok((await page.locator('#roomNote').innerText()).includes('手动'));
await page.locator('#roomSelections [data-room="night"]').click();
assert.equal(await page.locator('#roomArt').getAttribute('class'),'room-art night');
await page.screenshot({path:'test-results/rooms-mobile.png',fullPage:true});
await page.locator('#menuBtn').click();
await page.locator('[data-page="wardrobe"]').click();
assert.equal(await page.locator('#outfitSelections .outfit-card').count(),6);
await page.locator('#outfitSelections [data-outfit="mist"]').click();
assert.ok((await page.locator('.wardrobe-avatar .eli-illustration-main').getAttribute('src')).includes('outfit-mist.webp'));
await page.screenshot({path:'test-results/wardrobe-mobile.png',fullPage:true});
await page.locator('#menuBtn').click();
await page.locator('[data-page="hub"]').click();
await page.locator('#intakeCalories').fill('456');
await page.locator('#intakeForm button[type="submit"]').click();
await page.locator('#menuBtn').click();
await page.locator('[data-page="home"]').click();
assert.ok((await page.locator('#intakeValue').innerText()).includes('456'));
await page.locator('#menuBtn').click();
await page.locator('[data-page="settings"]').click();
assert.ok((await page.locator('#dataStatus').innerText()).includes('1 天'));
const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#exportBtn').click()]);
const path=await download.path();
const backup=JSON.parse(fs.readFileSync(path,'utf8'));
assert.equal(Object.keys(backup.life.intake).length,1);
assert.equal(backup.room,'night');
assert.equal(backup.outfit,'mist');
assert.ok(backup.life.healthUrl.includes('script.google.com'));
assert.ok(backup.life.ledgerUrl.includes('tinychub18'));
const width=await page.evaluate(()=>document.documentElement.scrollWidth);
assert.ok(width<=392,'Mobile horizontal overflow: '+width);
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: Mobile scenes, image wardrobe, local persistence, intake, all-data backup, no JS errors');
