import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
const main=page.locator('.character-panel .eli-illustration-main');
await main.waitFor();
assert.ok((await main.getAttribute('src')).includes('outfit-charcoal.webp'));
assert.ok(await main.evaluate(img=>img.complete&&img.naturalWidth>0));
assert.equal(await page.locator('.eli-art-reference').count(),0);
assert.equal(await page.locator('.character-panel svg').count(),0);
await page.locator('button.mini-outfit[data-look="cream"]').click();
assert.ok((await main.getAttribute('src')).includes('outfit-cream.webp'));
await page.locator('.character-panel [data-mood="happy"]').click();
assert.ok((await main.getAttribute('src')).includes('outfit-cream.webp'));
let saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('eli-home-mvp-v1')));
assert.equal(saved.look,'cream');
assert.equal(saved.mood,'happy');
assert.equal(await page.evaluate(()=>localStorage.getItem('eli-choice-look-v1')),'cream');
assert.equal(await page.evaluate(()=>localStorage.getItem('eli-choice-mood-v1')),'happy');
await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
await page.reload({waitUntil:'networkidle'});
assert.ok((await page.locator('.character-panel .eli-illustration-main').getAttribute('src')).includes('outfit-cream.webp'));
saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('eli-home-mvp-v1')));
assert.equal(saved.look,'cream');
assert.equal(saved.mood,'happy');
assert.equal(await page.locator('#heroSceneStrip button').count(),4);
await page.locator('#heroSceneStrip button[data-room="rain"]').click();
assert.equal(await page.locator('#hero').getAttribute('data-scene'),'rain');
await page.locator('button[data-go="rooms"]').first().click();
assert.equal(await page.locator('#roomSelections .selection-card').count(),4);
await page.locator('#roomSelections [data-room="night"]').click();
assert.equal(await page.locator('#roomArt').getAttribute('class'),'room-art night');
await page.locator('#menuBtn').click();
await page.locator('[data-page="wardrobe"]').click();
assert.equal(await page.locator('#outfitSelections .outfit-card').count(),6);
assert.equal(await page.locator('#wardrobePalette').count(),0);
await page.locator('#outfitSelections [data-look="rose"]').click();
await page.locator('.wardrobe-stage [data-mood="cheer"]').click();
const wardrobeImage=page.locator('.wardrobe-avatar .eli-illustration-main');
assert.ok((await wardrobeImage.getAttribute('src')).includes('outfit-rose.webp'));
assert.ok((await page.locator('#outfitSelections [data-look="rose"]').innerText()).includes('燕麦色'));
await page.locator('.wardrobe-stage [data-illustration-preview="mood"]').click();
assert.ok((await wardrobeImage.getAttribute('src')).includes('mood-cheer.webp'));
assert.equal(await page.locator('.eli-art-reference').count(),0);
assert.equal(await page.locator('.wardrobe-stage svg').count(),0);
saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('eli-home-mvp-v1')));
assert.equal(saved.look,'rose');
assert.equal(saved.mood,'cheer');
assert.equal(await page.evaluate(()=>localStorage.getItem('eli-choice-look-v1')),'rose');
assert.equal(await page.evaluate(()=>localStorage.getItem('eli-choice-mood-v1')),'cheer');
assert.ok((await page.locator('#outfitDescription').innerText()).includes('燕麦色'));
await page.screenshot({path:'test-results/wardrobe-mobile.png',fullPage:true});
await page.locator('#menuBtn').click();
await page.locator('[data-page="hub"]').click();
const today=await page.evaluate(()=>new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date()));
const sample={version:1,source:'日常有迹-GoogleAppsScript',exported_at:new Date().toISOString(),rows:[
{id:'n1',kind:'nutrition',date:today,calories:200,completeness:'partial'},
{id:'n2',kind:'nutrition',date:today,calories:125.5,completeness:'partial'},
{id:'n3',kind:'nutrition',date:today,calories:null},
{id:'w1',kind:'weight',date:today,weight:72.1}
]};
await page.locator('#healthImportFile').setInputFiles({name:'health-export.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(sample))});
assert.ok((await page.locator('#hubIntakeInfo').innerText()).includes('325.5 kcal'));
assert.ok((await page.locator('#healthImportStatus').innerText()).includes('不是实时同步'));
await page.locator('#menuBtn').click();
await page.locator('[data-page="home"]').click();
assert.ok((await page.locator('#intakeValue').innerText()).includes('325.5'));
assert.ok((await page.locator('#intakeStatus').innerText()).includes('非实时'));
await page.reload({waitUntil:'networkidle'});
assert.ok((await page.locator('#intakeValue').innerText()).includes('325.5'));
await page.locator('#menuBtn').click();
await page.locator('[data-page="hub"]').click();
await page.locator('#intakeCalories').fill('456');
await page.locator('#intakeForm button[type="submit"]').click();
await page.locator('#menuBtn').click();
await page.locator('[data-page="home"]').click();
assert.ok((await page.locator('#intakeValue').innerText()).includes('456'));
await page.locator('#menuBtn').click();
await page.locator('[data-page="settings"]').click();
assert.ok((await page.locator('#dataStatus').innerText()).includes('1 天「日常有迹」'));
const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#exportBtn').click()]);
const backup=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
assert.equal(backup.look,'rose');
assert.equal(backup.mood,'cheer');
assert.equal(backup.room,'night');
assert.equal(backup.life.healthImport.daily[today].calories,325.5);
assert.equal(backup.life.intake[today].calories,456);
assert.ok(backup.life.healthUrl.includes('script.google.com'));
const width=await page.evaluate(()=>document.documentElement.scrollWidth);
assert.ok(width<=392,'Mobile horizontal overflow: '+width);
assert.deepEqual(errors,[]);
const legacy=await browser.newPage({viewport:{width:390,height:844}});
await legacy.addInitScript(()=>{
  localStorage.setItem('eli-home-mvp-v1',JSON.stringify({version:1,outfit:'cream',color:'mist',mood:'calm',room:'day',diaries:[],memories:[]}));
  localStorage.setItem('eli-choice-outfit-v1','cream');
  localStorage.setItem('eli-choice-color-v1','mist');
  localStorage.setItem('eli-choice-mood-v1','calm');
});
await legacy.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
assert.ok((await legacy.locator('.character-panel .eli-illustration-main').getAttribute('src')).includes('outfit-cream.webp'));
const migrated=await legacy.evaluate(()=>JSON.parse(localStorage.getItem('eli-home-mvp-v1')));
assert.equal(migrated.version,2);
assert.equal(migrated.look,'cream');
assert.equal(migrated.mood,'calm');
assert.equal('color' in migrated,false);
await legacy.close();
await browser.close();
console.log('PASS: image-only character, real image-based outfit/color choice, separately saved expression preference, persisted room, real health JSON import, manual override, backup and mobile viewport');
